def build_case_block(tags):
    """The bash case statement that turns a condition tag into flags and levels."""
    lines = []
    for tag in tags:
        flags, levels, _, why = CONDITIONS[tag]
        lines.append(f'  # {why}')
        lines.append(f'  {tag}) NOISE_FLAGS="{flags}"; LEVELS="{levels}" ;;')
    return '\n'.join(lines)


