import json
import math
from pathlib import Path

# ---------------------------------------------------------------------------
# Representations
# ---------------------------------------------------------------------------
# The set was settled on 2026-08-26 and is enforced in the code: PDV
# (pdv), MHG-GNN, Avalon, ECFP4, ChemBERTa, Sort & Slice. mol2vec is
# deleted outright; one-hot SMILES and randomized SMILES still build but are
# refused by name in process_and_train.py parse_mmap, so a job that asked for
# them would raise rather than produce results with nowhere to go.
#
#   ALL_REPS  the six.
#   FP_REPS   binary fingerprints only. The Tanimoto kernel is defined on binary
#             vectors, so the Tanimoto GP can only run here.
#
# SORT & SLICE IS NOT A BINARY FINGERPRINT AND WAS REMOVED FROM FP_REPS
# 2026-08-31. It is built with sub_counts=True (process_and_train.py), and the
# featuriser multiplies each substructure by how often it occurs, so the vector
# holds small integers, not bits -- measured max 6 on ordinary drug-like
# molecules. models/models.py refuses the pairing at fit time:
#
#     if params['kernel_name'] != 'RBF' and not is_binary_matrix(x_train_full):
#         raise ValueError(...)
#
# So half of the Tanimoto script's tasks -- three of six in the screen, three of
# six in the main grid -- would have raised on every noise level and written an
# empty results file after their queue wait. Nothing caught it: the generator's
# own test checks emitted command lines against the argument parser, and this
# failure happens inside the model, long after parsing.
#
# Sort & Slice keeps its Gaussian-process row through gauche_rbf, which runs on
# every representation. Binarising the counts for the Tanimoto kernel would be a
# study decision about what is being compared, not a generator fix, and it must
# not be made silently.
ALL_REPS = ['ecfp4', 'pdv', 'mhggnn', 'avalon', 'chemberta', 'sns']
FP_REPS = ['ecfp4']

# ---------------------------------------------------------------------------
# Noise conditions
# ---------------------------------------------------------------------------
# Level grids, NOISE_DESIGN.md 6.4, both set by the range-finding run (5.5).
# Below 0.2 of the label spread the models are indistinguishable from clean;
# 1.5 is kept because it is the only level where the conditions separate at all.
DOSE_LEVELS = '0.0 0.2 0.3 0.5 0.75 1.0 1.5'
# Censoring is swept on its own axis -- the fraction of labels clipped at the
# assay limit. There is no knee; damage accelerates smoothly, becoming serious
# around 20% and severe past 30%.
CENSOR_LEVELS = '0.0 0.10 0.20 0.25 0.30 0.40 0.50'

# WHICH CONDITIONS EXIST, AND WHICH RUN AT FULL GRID, IS NOT DECIDED HERE.
#
# noise_conditions.json is the settled set, and it is read by tests on both
# injectors. This generator reads it too, rather than restating it: a restatement
# is how the two injectors drifted apart for the life of the project, and a job
# script that runs a condition the study does not recognise is the same failure
# one layer up.
#
# What DOES belong here is the translation from a condition name to the
# command-line flags that produce it, and which level grid it is swept on. That
# is the generator's actual job.
#
# Only flags that DIFFER from the process_and_train.py default are passed. The
# rest are echoed in full by the injector on every call (the "Rust command:" line
# in the job output), so provenance is captured without this file restating --
# and eventually contradicting -- the defaults. The single-setting decisions
# (nu, the outlier fraction, which end censoring clips) come from the settled
# file, spelled out on the command line so the job log records them.
# WHICH PAIRS THE UNCERTAINTY WORK RUNS, read and never restated.
#
# The author settled this on 2026-08-29: four models, three representations, the
# variational network on ChemBERTa alone. The same pairs on all four datasets,
# which was the ruling of 2026-08-28 -- "the same thing that happens on QM9
# happens on the others".
#
# It had been applied to the laboratory job generator and to nothing else. QM9
# has no uncertainty run of its own; its uncertainty rows fall out of this grid,
# so every model that emits one was cross-fitted on every representation. That is
# 11 models by 6 representations against the laboratory's 10 pairs, and the two
# halves could not be compared pair for pair.
#
# This restricts ONLY the uncertainty pass. Every model still trains on every
# representation for the accuracy results, the retention curves and the variance
# decomposition, none of which read an uncertainty column.
UNCERTAINTY_PAIRS_FILE = Path(__file__).resolve().parent.parent / 'uncertainty_pairs.json'
_PAIRS = json.loads(UNCERTAINTY_PAIRS_FILE.read_text())
# QM9 roster label -> the representations that model runs the uncertainty pass on.
UNCERTAINTY_PAIRS = {}
_pair_reps_all = [r['qm9'] for r in _PAIRS['representations']]
_canon_to_qm9_rep = {r['canonical']: r['qm9'] for r in _PAIRS['representations']}
for _m in _PAIRS['models']:
    _only = _PAIRS.get('model_representations', {}).get(_m['canonical'])
    UNCERTAINTY_PAIRS[_m['qm9']] = ([_canon_to_qm9_rep[c] for c in _only]
                                    if _only else list(_pair_reps_all))

# HOW MANY OF THE INNER FOLDS ARE ACTUALLY SCORED, per model.
#
# The out-of-fold pass splits the training molecules into `--oof-folds` folds and
# refits once per fold, so every molecule is scored by a model that never saw its
# label. Scoring FEWER folds than were cut keeps that property exactly -- the
# molecules in a scored fold are still scored out of fold -- and costs one refit
# per scored fold instead of five. The molecules in the unscored folds are left
# blank, so it buys the cost back with coverage, not with correctness.
#
# NGBoost is the only model that needs it, and it needs it because it pays for
# two different questions at once. Three seeds give it a model-uncertainty term
# at all (a single distributional fit has nothing to disagree with, added
# 2026-08-30 in c2aec9d); the out-of-fold pass gives per-molecule rows whose
# labels were corrupted. The two multiply: three seeds times six fits is
# EIGHTEEN fits per training run, which prices the main grid task at 606 hours --
# 25 days against a 30-day partition limit, with nothing spare for a hiccup.
#
# Three seeds and one scored fold is six fits, 202 hours, which is exactly what
# NGBoost cost before the seeds landed. What is given up is per-molecule coverage
# on NGBoost: a fifth of the training molecules get an out-of-fold row instead of
# all of them. That is the input to the which-molecules question, which NGBoost is
# not the model that answers -- and the decomposition claim it IS on the list for
# is a population statement that does not read those rows at all
# (uncertainty_pairs.json, `_which_question_this_answers`).
#
# Set to 0, or leave a model out, to score every fold that was cut.
# HOW MANY INNER FOLDS EACH MODEL ACTUALLY SCORES.
#
# Scoring fewer folds than were cut keeps the property that matters exactly -- a
# molecule in a scored fold is still scored by a model that never saw its label
# -- and costs one refit per scored fold instead of five. What is given up is
# per-molecule COVERAGE: the molecules in the unscored folds are left blank.
#
# NGBOOST NEEDS IT AGAIN, for a different reason than the first time. It was set
# to 1 on 2026-08-30 because the seed ensemble made NGBoost eighteen fits per
# training run; the ensemble was withdrawn the next day (RERUN_PLAN.md 2.30) and
# this went empty. Then NGBoost's wall clock was MEASURED at 166 hours per 110
# training runs, against the 47 it had been guessed at, and at six fits per run
# that prices a main-grid task at 714 hours -- 29.8 days against the long
# partition's 30-day limit, with nothing spare. It would queue for days and be
# killed at the wall, which loses the whole task.
#
#   scored folds    wall clock    per-molecule coverage
#        5             714h  ✗           100%
#        4             595h  ✗            80%
#        3             476h  ✓            60%
#        1             238h  ✓            20%
#
# THREE is the most coverage that fits inside the guard's 540-hour ceiling
# (three quarters of the partition limit, so a slow node does not lose the job).
# NGBoost is also not the model the per-molecule question rests on -- it has no
# epistemic term at all (2.30), and its place on the decomposition list was
# withdrawn -- so coverage is the right thing to spend here rather than seeds or
# levels.
OOF_FOLDS_SCORED = {'ngboost': 3}

NOISE_CONDITIONS_FILE = Path(__file__).resolve().parent.parent / 'noise_conditions.json'
_SETTLED = json.loads(NOISE_CONDITIONS_FILE.read_text())
_SETTINGS = _SETTLED['settings_that_follow']

CONDITION_FLAGS = {
    'gaussian':        ('--noise-shape gaussian --noise-targeting uniform', DOSE_LEVELS),
    'grouped_wider':   ('--noise-shape gaussian --noise-targeting grouped_wide', DOSE_LEVELS),
    'grouped_shifted': ('--noise-shape gaussian --noise-targeting grouped_shift', DOSE_LEVELS),
    'censoring':       (f"--noise-targeting censoring "
                        f"--censor-side {_SETTINGS['censor_side']}", CENSOR_LEVELS),
    'student_t_nu5':   (f"--noise-shape student_t --noise-targeting uniform "
                        f"--nu {_SETTINGS['nu']}", DOSE_LEVELS),
    'outlier_p10':     (f"--noise-shape gaussian --noise-targeting outlier "
                        f"--outlier-p {_SETTINGS['outlier_p']}", DOSE_LEVELS),
    'laplace':         ('--noise-shape laplace --noise-targeting uniform', DOSE_LEVELS),
}

# The clean level is run ONCE, under the reference condition, and copied into the
# others by copy_zero_rows.py after the array finishes.
#
# At level 0 the pipeline does not add noise at all -- it switches the noise step
# off for every split -- and the replicate seed depends only on the replicate
# number, so the clean run is bit-identical whichever condition it is labelled
# with. Measured on 400 QM9 molecules with the random forest on ECFP4: all four
# conditions returned R2 = 0.7579128047581825 and RMSE = 0.5176004014184159, to
# the last digit.
#
# Running it four times costs 11% of the QM9 grid to recompute a number we
# already have. It cannot simply be dropped, because auc_norm divides each
# condition's curve by that condition's OWN clean accuracy, so a condition with
# no clean row has nothing to divide by -- hence the copy.
REFERENCE_CONDITION = 'gaussian'

# CONDITIONS THAT RUN THEIR OWN CLEAN LEVEL, on top of the reference.
#
# The copy above is sound for ACCURACY and unsound for the uncertainty question,
# and nobody joined the two facts up. copy_zero_rows.py refuses any file whose
# name contains `_uncertainty_values` -- correctly, because it cannot invent
# per-molecule numbers -- so a condition without its own clean level gets its
# accuracy baseline and no uncertainty baseline.
#
# That baseline is not optional and it is not borrowable. "Is the model less
# certain where the labels are unreliable" is answered by correlating the
# predicted uncertainty against the level-free shape of the noise, then
# SUBTRACTING the same correlation at level zero -- because a model can look
# less certain about those molecules for a boring reason, such as their being
# the large ones. The zero-level model saw the same labels and no corruption, so
# its correlation is exactly that confound.
#
# Borrowing the reference condition's clean run does not work: the shape column
# is what differs between conditions at level zero, and the reference condition
# hits every molecule equally, so it has no shape to subtract. Without its own
# clean row the effect comes out NaN -- an empty table, not a wrong one.
#
# WHY ONLY CENSORING. Author's decision, 2026-08-28, on the evidence in
# RERUN_PLAN.md 3.1f. Of the seven conditions, four deliver the same amount to
# every molecule, so their shape is flat and the correlation is undefined rather
# than zero. Of the three with a shape, `grouped_wider` is keyed to the scaffold
# group and the out-of-fold pass splits on that SAME array, so the group is
# hidden from the fit being asked about; `outlier_p10` picks its victims at
# random. Both are structural nulls whatever is measured. Censoring is keyed to
# the label, so it is learnable on any split -- it is the only condition on which
# the question has an answer, and the only one whose clean level buys something.
#
# Cost: censoring runs on about five model-and-representation pairs on QM9, so
# this is roughly 45 extra training runs across the main grid. Adding the two
# nulls as well would be about 5.3% of the screen and of the main grid, and buys
# a measured zero where the design already predicts one.
NEEDS_OWN_CLEAN_LEVEL = {'censoring'}


def build_uncertainty_block(model, unc_reps, oof_folds, oof_scored=0):
    """The shell that decides whether THIS array task runs the uncertainty pass.

    The pass costs `oof_folds` extra fits on top of the training run, and it is
    worth spending only on the settled pairs (`uncertainty_pairs.json`). Which
    representation a task has is not known until the array dispatches, so the
    choice is a case statement rather than a flag baked into the command.

    A model that emits no per-molecule uncertainty at all gets an empty variable
    and a line saying so, rather than nothing -- a silent absence and a decision
    read the same in a job log.
    """
    if not unc_reps:
        return ('OOF_FLAGS=""\n'
                f'echo "=== out-of-fold pass: {model} is on no settled pair here, '
                'so test rows only"')
    cases = ' | '.join(unc_reps)
    return (
        '# The out-of-fold uncertainty pass, on the settled pairs only\n'
        '# (uncertainty_pairs.json). It refits once per inner fold, so a run on a\n'
        '# settled pair costs %d fits instead of one -- a task on any other\n'
        '# representation must not pay for it. `-u True` is NOT restricted: it is\n'
        '# free and it writes the test rows either way.\n'
        'case "$rep" in\n'
        '  %s) OOF_FLAGS="--oof-folds %d%s" ;;\n'
        '  *) OOF_FLAGS="" ;;\n'
        'esac\n'
        'if [ -n "$OOF_FLAGS" ]; then\n'
        '    echo "=== out-of-fold pass: settled pair %s/$rep -> $OOF_FLAGS"\n'
        'else\n'
        '    echo "=== out-of-fold pass: %s/$rep is not a settled pair, test rows only"\n'
        'fi' % (1 + (oof_scored or oof_folds), cases, oof_folds,
                (f' --oof-folds-scored {oof_scored}' if oof_scored else ''),
                model, model))


def levels_for(name, levels):
    """The levels a condition actually runs.

    The reference condition runs the clean one, and so does any condition that
    needs its OWN clean level as the control for the uncertainty question. Every
    other condition has its clean ACCURACY row filled in afterwards by
    copy_zero_rows.py, which is sound because at level zero the fit is
    bit-identical whichever condition labels it.
    """
    if name == REFERENCE_CONDITION or name in NEEDS_OWN_CLEAN_LEVEL:
        return levels
    return ' '.join(v for v in levels.split() if float(v) != 0.0)


# Conditions the settled file restricts to a subset of model-and-representation pairs on
# QM9. Censoring is the only one today: the question there is how big the effect is, not
# which model resists it best, so it runs on about five pairs instead of all 78
# (RERUN_PLAN.md 13.13). The scope is QM9 only -- censoring stays a full condition in the
# uncertainty runs. Read from the file rather than hardcoded, so the file stays the place
# the decision lives.
