# name -> (flags, level grid, runs at full grid in stage 1, why -- the settled
# file's own words, so the job script header carries the reason with it)
CONDITIONS = {}
for _group in ('stage_1_full_grid', 'stage_2_depth_only'):
    for _entry in _SETTLED[_group]:
        _name = _entry['name']
        if _name not in CONDITION_FLAGS:
            raise SystemExit(
                f"{NOISE_CONDITIONS_FILE.name} names the condition '{_name}' but this generator "
                f"does not know how to ask for it. Add it to CONDITION_FLAGS, or the study runs "
                f"a set the job scripts cannot produce.")
        _flags, _levels = CONDITION_FLAGS[_name]
        CONDITIONS[_name] = (_flags, levels_for(_name, _levels),
                             _group == 'stage_1_full_grid', _entry['why'])

_unused = sorted(set(CONDITION_FLAGS) - set(CONDITIONS))
if _unused:
    raise SystemExit(
        f"this generator can emit condition(s) {_unused} that {NOISE_CONDITIONS_FILE.name} does "
        f"not run. Either add them there with their evidence, or take them out of "
        f"CONDITION_FLAGS -- a condition nobody decided to run is how an unjustified cell gets "
        f"into the study.")

