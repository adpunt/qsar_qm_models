#!/usr/bin/env python3
"""Generate the SLURM job arrays for the QM9 re-run.

WHY EVERYTHING ABOVE ZERO NOISE HAS TO BE REDONE
------------------------------------------------
The noise map is keyed by TRAINING index, and write_data restarted its counter
for every split -- so validation and test molecules were handed the noise drawn
for the training molecule at the same position. Held-out labels were corrupted
contrary to the Methods, AND the corruption was attached to the wrong molecules.
Every QM9 R2 above zero noise was scored against a moving target.

Fixed in rust/src/main.rs (apply_noise flag, true only for the training call).
The fix is in the repo; the binary must be REBUILT on the cluster.

Results at zero noise are unaffected -- process_and_train.py switches the noise
path off for all splits at level 0. They are re-run here anyway because splicing
two runs is more error-prone than re-running one grid, and zero is 1/7th of the
cost.

WHAT CHANGED ON 2026-08-27, AND WHY THE OLD SCRIPTS COULD NOT RUN
-----------------------------------------------------------------
This generator was written against the noise scheme that has since been replaced
(NOISE_DESIGN.md). It emitted `--sigma` and `--noise-strategy`, and
process_and_train.py now refuses both BY NAME (:420-431) rather than ignoring
them, because a job written against the old scheme would otherwise run silently
under the new one where the level means something different. It also emitted
`-b` for the replicate count, and two representations -- mol2vec and one-hot
SMILES -- that were dropped from the study on 2026-08-26 and are refused by name
in parse_mmap (:1173, :1199). Every generated script would therefore have failed
at argument parsing, or in the reader.

Nothing generated by the old version is recoverable or worth recovering: the
.sh files are not in version control (SLURM scripts are copied to the cluster,
not committed), so this file IS the artefact.

WHAT A CONDITION IS NOW
-----------------------
The old six "strategies" were one strategy at six doses (RERUN_PLAN.md 2.2).
The replacement separates two things that were tangled together:

  --noise-shape      the shape of each individual draw   (gaussian, student_t, laplace)
  --noise-targeting  who gets hit and how hard           (uniform, grouped_wide,
                                                          grouped_shift, outlier, censoring)

and every combination delivers the SAME amount of noise at the same level, so
the conditions are comparable to each other. A "condition" below is one
(shape, targeting) pair plus the parameters that pair needs. The level grids
come from the range-finding run, NOISE_DESIGN.md 6.4 -- seven dose levels for
the zero-mean conditions, seven censoring fractions for censoring, which is not
zero-mean and cannot be dose-matched.

THE STAGES
----------
RERUN_PLAN.md 13.1, agreed 2026-08-26. The replicate seed depends only on the
replicate index, so stage 0 IS replicate 0 of stage 1 and is reused rather than
thrown away -- which is why --stage 1 starts at iteration 1 and why both stages
write to the same file.

  stage 0  screen     every model x every rep, the stage-1 conditions, 1 replicate
  stage 1  breadth    the same grid, replicates 1-9 appended to stage 0's
  stage 2  depth      chosen models x chosen reps, ALL conditions, 10 replicates

Stage 2 cannot be generated blind -- which models and representations go deep is
open (13.1 item 4) and cannot be chosen before stage 0 has run -- so --stage 2
requires --models and --reps explicitly.

THE GRID
--------
13 models x 6 representations x {conditions} x 7 levels x {replicates}.
Model and representation are the two factors of the variance decomposition, so
neither can be cut without gutting the paper's first question.

One array TASK per (condition, representation); one SCRIPT per model.
"""
